def detect_site(text):
    t = re.sub(r'\s+', '', text)
    found = set()
    for site, kws in SITE_KEYWORDS.items():
        for kw in kws:
            if kw in t:
                found.add(site)
                break
    return found


def route(text):
    t = re.sub(r'\s+', '', text)
    if not t: return []

    sites = detect_site(t)
    if not sites: return []

    results = []
    for site in sites:
        rules = ROUTING.get(site, [])
        matched = False
        for keywords, tpl_names in rules:
            if all(kw in t for kw in keywords):
                for idx, name in enumerate(tpl_names):
                    score = 0.90 - idx * 0.05
                    results.append({'name': name, 'score': round(score, 2), 'site': site, 'method': 'route'})
                matched = True
                break

        if not matched:
            fb = FALLBACK_TPL.get(site, '')
            if fb:
                results.append({'name': fb, 'score': 0.50, 'site': site, 'method': 'fallback'})

    return results
