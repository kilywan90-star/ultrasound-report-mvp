def run_test(case_id: int, text: str, exam_type: str) -> dict:
    """运行单条测试, 返回完整结果字典"""
    t0 = time.time()

    # Step 1: 意图识别 - 精确模板匹配
    candidates = match_exact_template(text, exam_type)
    if not candidates:
        return {
            "id": case_id, "input": text, "exam_type": exam_type,
            "template_matched": "无匹配", "score": 0,
            "template_original": "", "filled_output": text,
            "method": "no_match", "elapsed_ms": 0,
            "warnings": "未匹配到任何模板",
            "top3_candidates": "",
        }

    best = candidates[0]
    template_name = best["tpl_name"]
    score = best["score"]
    info1 = best.get("info1", "")

    # 如果 INFO1 太短, 从 template_loader 补充
    if not info1 or len(info1) < 10:
        tpl = get_template_by_name(template_name)
        if tpl:
            info1 = tpl.get("info1", "")

    # Step 2: 解析模板变量
    parsed = parse_template_variables(info1)

    # Step 3: 模板填充 (正则兜底, 因为测试中无法调用LLM)
    filled = basic_regex_fill(text, info1) if info1 else text

    elapsed = (time.time() - t0) * 1000

    # 生成警告
    warnings = []
    if parsed["blank_placeholders"] > 5:
        warnings.append(f"模板有{parsed['blank_placeholders']}个空白占位符")
    if parsed["total_variables"] > parsed["option_groups"].__len__() * 2:
        warnings.append(f"模板变量较多({parsed['total_variables']}个), 建议手工核对")
    if not info1 or len(info1) < 20:
        warnings.append("模板原文内容较短, 可能不够完整")
    if score < 100:
        warnings.append(f"匹配置信度较低({score}), 建议人工确认")

    # 脱敏处理输入文本中的姓名
    clean_text = re.sub(r'(?:患者|病人)\s*[:：]?\s*[一-龥]{2,4}', '[患者]', text)

    return {
        "id": case_id,
        "input": clean_text[:300],
        "exam_type": exam_type,
        "template_matched": f"{best.get('level2','')}/{best.get('level3','')} - {template_name}",
        "score": score,
        "template_original": info1[:200] if info1 else "(无模板原文)",
        "filled_output": re.sub(r'<[^>]+>', '', filled)[:300],
        "method": "anchored_regex",
        "elapsed_ms": round(elapsed, 1),
        "warnings": "; ".join(warnings) if warnings else "(无警告)",
        "top3_candidates": "; ".join(f"{c['tpl_name']}({c['score']})" for c in candidates[:3]),
        "variable_count": parsed["total_variables"],
        "option_count": len(parsed["option_groups"]),
        "blank_count": parsed["blank_placeholders"],
    }


